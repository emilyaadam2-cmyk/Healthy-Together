-- Healthy Together: database additions / verification
-- Run only after reviewing existing tables. This script uses IF NOT EXISTS where possible.
-- Never put a service-role key in the browser. Keep Row Level Security enabled.

create table if not exists public.wins (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  description text not null,
  points integer not null default 5,
  created_at timestamptz not null default now()
);

alter table public.wins enable row level security;

drop policy if exists "Users can manage their own wins" on public.wins;
create policy "Users can manage their own wins"
on public.wins for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- Ensure the private weight table is user-only. If these policies already exist,
-- the DROP statements replace only policies with these exact names.
alter table public.weight_entries enable row level security;
drop policy if exists "Users can manage their own weight entries" on public.weight_entries;
create policy "Users can manage their own weight entries"
on public.weight_entries for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

